const TEXT: Record<Lang, Record<TextKey, string>> = { zh, en };

export function translate(
  lang: Lang,
  key: TextKey,
  values: Record<string, string | number> = {},
): string {
  return TEXT[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

export interface LangValue {
  lang: Lang;
  t: (key: TextKey, values?: Record<string, string | number>) => string;
}
export const LangContext = createContext<LangValue>({
  lang: "zh",
  t: (key, values) => translate("zh", key, values),
});
export const useLang = (): LangValue => useContext(LangContext);
